/// The mouse buttons `mouseButtonCodes.h` names. C++ buttons 1..8 start at 1
/// (GLFW); the raw number of anything past the three named buttons is kept.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum MouseButton {
    Left,
    Right,
    Middle,
    Other(u8),
}
